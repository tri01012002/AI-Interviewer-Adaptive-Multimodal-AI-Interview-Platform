"""Child-process entry points for the PostgreSQL multi-worker tests.

Every function here runs in a fresh interpreter started with the ``spawn``
method, so each worker builds its own engine and connection pool from
DATABASE_URL exactly like a separately deployed worker process.

Side effects (LLM calls, e-mail deliveries) are written to a ledger table in
the ``reliability_probe`` schema through an autocommit connection. The ledger
row therefore survives even when the worker dies before its own transaction
commits, which is what lets the tests count real side effects instead of only
inspecting final row states.
"""

from __future__ import annotations

import json
import os
import threading
import time
import traceback
from uuid import uuid4

from fastapi import HTTPException
from sqlalchemy import create_engine, text

from services import candidate_communication_service
from services.candidate_application_service import CandidateApplicationService
from services.candidate_communication_service import CandidateCommunicationService
from services.email_provider import EmailDeliveryResult
from services.interview_scheduling_service import (
    InterviewScheduleTransition,
    InterviewSchedulingService,
)
from services.recruitment_campaign_orchestrator import RecruitmentCampaignOrchestrator
from services.recruitment_campaign_worker import RecruitmentCampaignWorker
from services.tenant_authorization import TenantContext

LEDGER_TABLE = "reliability_probe.side_effects"
CRASH_EXIT_CODE = 137

_ledger_engine = None


def ledger_engine():
    global _ledger_engine
    if _ledger_engine is None:
        _ledger_engine = create_engine(
            os.environ["DATABASE_URL"], isolation_level="AUTOCOMMIT", pool_size=1
        )
    return _ledger_engine


def record_side_effect(kind: str, reference: str) -> None:
    with ledger_engine().connect() as connection:
        connection.execute(
            text(
                f"INSERT INTO {LEDGER_TABLE} (kind, reference, pid) "
                "VALUES (:kind, :reference, :pid)"
            ),
            {"kind": kind, "reference": reference, "pid": os.getpid()},
        )


class CountingJobDesignProvider:
    """Structured LLM stand-in that records each call before answering."""

    provider_name = "test-fixture"
    model = "test-fixture"
    prompt_version = "test-fixture-v1"

    def __init__(self, *, delay: float = 0.0) -> None:
        self.delay = delay

    def generate(self, system_instruction: str, user_content: str) -> str:
        raise AssertionError("Job design must use the typed structured provider API")

    def generate_structured(self, system_instruction: str, user_content: str, schema):
        brief = json.loads(user_content)["director_hiring_brief"]
        record_side_effect("llm_job_design", brief)
        time.sleep(self.delay)
        return schema.model_validate(
            {"job_description": f"Generated by worker process {os.getpid()}."}
        )


class CountingEmailProvider:
    """E-mail stand-in; the ledger row is the 'message left the system' event."""

    provider_name = "smtp"

    def __init__(
        self,
        *,
        outcome: str = "accepted",
        delay: float = 0.0,
        crash_after_send: bool = False,
    ) -> None:
        self.outcome = outcome
        self.delay = delay
        self.crash_after_send = crash_after_send

    def deliver(self, request) -> EmailDeliveryResult:
        record_side_effect("email", request.communication_id)
        if self.crash_after_send:
            # Simulates SIGKILL after the provider accepted the message but
            # before the worker recorded that outcome in the database.
            os._exit(CRASH_EXIT_CODE)
        time.sleep(self.delay)
        return EmailDeliveryResult(
            outcome=self.outcome,
            provider_name="smtp",
            provider_message_id=f"probe-{uuid4().hex[:16]}",
            error_class=(
                "provider_temporary_failure"
                if self.outcome == "retryable_not_accepted"
                else None
            ),
        )


def _status(result) -> str | None:
    return None if result is None else result.status


def dispatch_campaign(*, llm_delay: float = 0.0) -> list[str]:
    results = RecruitmentCampaignOrchestrator.dispatch_once(
        limit=100, provider=CountingJobDesignProvider(delay=llm_delay)
    )
    return [result.status for result in results]


def run_execution(*, execution_id: str, llm_delay: float = 0.0) -> str | None:
    return _status(
        RecruitmentCampaignOrchestrator.run_dispatched(
            execution_id, provider=CountingJobDesignProvider(delay=llm_delay)
        )
    )


def deliver(*, communication_id: str, **provider_options) -> str | None:
    return _status(
        CandidateCommunicationService.process_dispatched(
            communication_id, CountingEmailProvider(**provider_options)
        )
    )


def discover_and_deliver(**provider_options) -> list[str | None]:
    return [
        _status(
            CandidateCommunicationService.process_dispatched(
                communication_id, CountingEmailProvider(**provider_options)
            )
        )
        for communication_id in CandidateCommunicationService.discover_eligible(50)
    ]


def confirm_schedule(
    *, schedule_id: str, version: int, organization_id: str, actor_user_id: str
) -> str:
    try:
        return InterviewSchedulingService.confirm(
            schedule_id,
            TenantContext(
                actor_user_id=actor_user_id,
                organization_id=organization_id,
                role="recruiter",
            ),
            InterviewScheduleTransition(expected_version=version),
        ).status
    except HTTPException as exc:
        return f"http_{exc.status_code}"


def advance_application(*, application_id: str) -> str | None:
    try:
        result = RecruitmentCampaignOrchestrator.advance_application_once(application_id)
    except HTTPException as exc:
        return f"http_{exc.status_code}"
    return None if result is None else result.action


def process_application(*, application_id: str) -> str | None:
    return _status(CandidateApplicationService.process_dispatched(application_id))


def run_worker_loop(*, seconds: float, **provider_options) -> str:
    """Run the real polling loop, then stop it the way SIGTERM does."""
    candidate_communication_service.create_email_provider = (
        lambda: CountingEmailProvider(**provider_options)
    )
    stop_event = threading.Event()
    worker = RecruitmentCampaignWorker(
        concurrency=2,
        poll_seconds=0.2,
        stop_event=stop_event,
        provider=CountingJobDesignProvider(),
    )
    timer = threading.Timer(seconds, stop_event.set)
    timer.start()
    try:
        worker.run()
    finally:
        timer.cancel()
    return "stopped"


TASKS = {
    "dispatch_campaign": dispatch_campaign,
    "run_execution": run_execution,
    "deliver": deliver,
    "discover_and_deliver": discover_and_deliver,
    "confirm_schedule": confirm_schedule,
    "advance_application": advance_application,
    "process_application": process_application,
    "run_worker_loop": run_worker_loop,
}


def worker_main(task: str, kwargs: dict, barrier, results) -> None:
    """Process target: wait for every sibling, then run one task."""
    try:
        kwargs = dict(kwargs)
        start_after = kwargs.pop("start_after", 0)
        barrier.wait(timeout=120)
        time.sleep(start_after)
        outcome = TASKS[task](**kwargs)
        results.put((os.getpid(), "ok", outcome))
    except BaseException as exc:  # reported to the parent, never swallowed
        results.put(
            (
                os.getpid(),
                "error",
                f"{type(exc).__name__}: {exc}\n{traceback.format_exc(limit=8)}",
            )
        )
