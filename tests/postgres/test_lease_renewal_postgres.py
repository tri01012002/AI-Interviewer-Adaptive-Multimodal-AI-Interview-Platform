def _execution_id(campaign_id: str) -> str:
    RecruitmentCampaignOrchestrator.discover_eligible(100)
    with SessionLocal() as session:
        return session.execute(
            select(RecruitmentCampaignExecutionRecord.id).where(
                RecruitmentCampaignExecutionRecord.campaign_id == campaign_id
            )
        ).scalar_one()


def _renewal_threads() -> list[str]:
    return [
        thread.name
        for thread in threading.enumerate()
        if thread.name.startswith(THREAD_NAME_PREFIX) and thread.is_alive()
    ]


def test_execution_longer_than_lease_is_renewed_and_cannot_be_reclaimed(
    client, monkeypatch
):
    monkeypatch.setenv("CAMPAIGN_WORKER_LEASE_SECONDS", str(SHORT_LEASE_SECONDS))
    tenant = create_tenant(client)
    campaign_id, brief = unique_llm_campaign(client, tenant)
    execution_id = _execution_id(campaign_id)

    owner, contender = run_workers(
        (
            "run_execution",
            {"execution_id": execution_id, "llm_delay": SHORT_LEASE_SECONDS * 2.5},
        ),
        # Without renewal the lease would have expired well before this point.
        after(("run_execution", {"execution_id": execution_id}), SHORT_LEASE_SECONDS + 3),
    )

    with SessionLocal() as session:
        execution = session.get(RecruitmentCampaignExecutionRecord, execution_id)
        campaign = session.get(RecruitmentCampaignRecord, campaign_id)
    assert side_effects("llm_job_design", brief) == [owner["pid"]]
    assert execution.attempt_count == 1
    assert execution.status == "waiting_for_approval"
    assert execution.lease_token is None
    assert campaign.job_description == f"Generated by worker process {owner['pid']}."
    # The contender found a live, renewed lease: it neither ran nor finished it.
    assert contender["outcome"] in {"running", None}


def test_delivery_longer_than_lease_is_renewed_sent_once_and_not_swept(
    client, tmp_path, monkeypatch
):
    monkeypatch.setenv("CAMPAIGN_WORKER_LEASE_SECONDS", str(SHORT_LEASE_SECONDS))
    tenant, _, _, _, application_id = create_screened_application(
        client, tmp_path, monkeypatch
    )
    communication_id = approve_communication(client, tenant, application_id, "pg-renew-1")

    sender, _sweeper = run_workers(
        ("deliver", {"communication_id": communication_id, "delay": SHORT_LEASE_SECONDS + 5}),
        after(("discover_and_deliver", {}), SHORT_LEASE_SECONDS + 2),
    )

    with SessionLocal() as session:
        communication = session.get(CandidateCommunicationRecord, communication_id)
        expired_events = session.scalar(
            select(func.count(CandidateCommunicationEventRecord.id)).where(
                CandidateCommunicationEventRecord.communication_id == communication_id,
                CandidateCommunicationEventRecord.event_type
                == "communication_lease_expired",
            )
        )
    assert side_effects("email", communication_id) == [sender["pid"]]
    assert communication.status == "sent"
    assert communication.attempt_count == 1
    assert expired_events == 0


def test_renewal_never_revives_an_expired_or_foreign_lease(client):
    tenant = create_tenant(client)
    campaign_id, _brief = unique_llm_campaign(client, tenant)
    execution_id = _execution_id(campaign_id)
    now = datetime.now(UTC)
    with SessionLocal.begin() as session:
        session.execute(
            update(RecruitmentCampaignExecutionRecord)
            .where(RecruitmentCampaignExecutionRecord.id == execution_id)
            .values(
                status="running",
                lease_token="owner-token",
                lease_expires_at=now + timedelta(seconds=30),
            )
        )

    assert RecruitmentCampaignOrchestrator._renew_execution_lease(execution_id, "owner-token")
    assert not RecruitmentCampaignOrchestrator._renew_execution_lease(
        execution_id, "stale-token"
    )

    with SessionLocal.begin() as session:
        session.execute(
            update(RecruitmentCampaignExecutionRecord)
            .where(RecruitmentCampaignExecutionRecord.id == execution_id)
            .values(lease_expires_at=now - timedelta(seconds=1))
        )
    assert not RecruitmentCampaignOrchestrator._renew_execution_lease(
        execution_id, "owner-token"
    )
    with SessionLocal() as session:
        execution = session.get(RecruitmentCampaignExecutionRecord, execution_id)
        expires = execution.lease_expires_at
    if expires.tzinfo is None:
        expires = expires.replace(tzinfo=UTC)
    assert expires < datetime.now(UTC)


def test_expired_lease_at_attempt_limit_moves_to_needs_attention(client):
    tenant = create_tenant(client)
    campaign_id, brief = unique_llm_campaign(client, tenant)
    execution_id = _execution_id(campaign_id)
    with SessionLocal.begin() as session:
        execution = session.get(RecruitmentCampaignExecutionRecord, execution_id)
        session.execute(
            update(RecruitmentCampaignExecutionRecord)
            .where(RecruitmentCampaignExecutionRecord.id == execution_id)
            .values(
                status="running",
                attempt_count=execution.max_attempts,
                lease_token="crashed-worker",
                lease_expires_at=datetime.now(UTC) - timedelta(seconds=1),
            )
        )

    result = RecruitmentCampaignOrchestrator.run_dispatched(
        execution_id, provider=CountingJobDesignProvider()
    )

    assert result is not None and result.status == "needs_attention"
    with SessionLocal() as session:
        execution = session.get(RecruitmentCampaignExecutionRecord, execution_id)
    assert execution.failure_code == "attempt_limit_reached"
    assert execution.lease_token is None
    assert side_effects("llm_job_design", brief) == []


def test_worker_shutdown_during_long_task_finishes_and_stops_renewal(
    client, monkeypatch
):
    monkeypatch.setattr(settings, "CAMPAIGN_WORKER_LEASE_SECONDS", 2)
    monkeypatch.setattr(settings, "CAMPAIGN_WORKER_LEASE_RENEWAL_SECONDS", None)
    tenant = create_tenant(client)
    campaign_id, brief = unique_llm_campaign(client, tenant)
    renewals: list[int] = []
    original_exit = LeaseRenewal.__exit__

    def recording_exit(self, *args):
        original_exit(self, *args)
        renewals.append(self.renewals)

    monkeypatch.setattr(LeaseRenewal, "__exit__", recording_exit)
    stop_event = threading.Event()
    worker = RecruitmentCampaignWorker(
        concurrency=1,
        poll_seconds=0.2,
        stop_event=stop_event,
        provider=CountingJobDesignProvider(delay=5.0),
    )
    runner = threading.Thread(target=worker.run, name="test-worker-loop")
    runner.start()
    deadline = time.monotonic() + 15
    while not side_effects("llm_job_design", brief) and time.monotonic() < deadline:
        time.sleep(0.1)
    # Ask for shutdown while the 5 s job design call is in flight (lease = 2 s).
    stop_event.set()
    runner.join(timeout=30)

    assert not runner.is_alive()
    assert _renewal_threads() == []
    # The shared test database may hold other eligible executions; this task's
    # 5 s call with a 2 s lease must have been renewed several times.
    assert renewals and max(renewals) >= 2
    with SessionLocal() as session:
        execution = session.execute(
            select(RecruitmentCampaignExecutionRecord).where(
                RecruitmentCampaignExecutionRecord.campaign_id == campaign_id
            )
        ).scalar_one()
    assert execution.status == "waiting_for_approval"
    assert execution.attempt_count == 1
    assert len(side_effects("llm_job_design", brief)) == 1
